// Writes resources/THIRD_PARTY_LICENSES.txt (#482): the name, version, license and license text of
// every npm library the packaged app ships, the production dependencies (app.asar) and, with their
// own dependencies, the devDependencies scripts/build-3d.js bundles into generated/ (three, react).
// scripts/package.js ships the file in the app's resources/ folder. Run it after a dependency change:
//   npm run licenses
// Exports collect and render for the tests; writes the file only when run directly.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const OUT = path.join(root, 'resources', 'THIRD_PARTY_LICENSES.txt');
// devDependencies bundled into generated/ by scripts/build-3d.js
const BUNDLED = [
  '@react-three/fiber',
  'react',
  'react-dom',
  'three',
];
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.|-|$)/i;

// The package folder of `name`, resolved from `fromDir` like Node does (nearest node_modules up).
function packageDir(name, fromDir) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name);
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate;
    if (path.dirname(dir) === dir) return null;
  }
}

// Every package reached from the root names (with dependencies and optionalDependencies), sorted by
// name and version: { name, version, license, text }. A missing optional package is skipped; a private
// package (a workspace of this repository) is walked but not listed.
function collect(names, base = root) {
  const seen = new Map();
  const visit = (name, fromDir) => {
    const dir = packageDir(name, fromDir);
    if (!dir || seen.has(dir)) return;
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const files = fs.readdirSync(dir).filter((f) => LICENSE_FILE.test(f)).sort();
    const text = files.map((f) => fs.readFileSync(path.join(dir, f), 'utf8').trim()).join('\n\n');
    const license = typeof pkg.license === 'object' ? pkg.license.type : pkg.license;
    // this repository's own workspace packages (private, phase 2 of docs/reorganisation-study-2026-10.md)
    // are not third parties: only what they depend on is listed
    seen.set(dir, pkg.private ? null : { name: pkg.name || name, version: pkg.version, license: license || 'UNKNOWN', text });
    for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies })) visit(dep, dir);
  };
  for (const name of names) visit(name, base);
  const key = (p) => `${p.name}@${p.version}`;
  return [...new Map([...seen.values()].filter(Boolean).map((p) => [key(p), p])).values()]
    .sort((a, b) => key(a).localeCompare(key(b)));
}

function render(packages) {
  const header = [
    'Third-party licenses of the npm libraries shipped with Multiagent Orchestrator.',
    'Generated by scripts/third-party-licenses.js (npm run licenses); see THIRD_PARTY_NOTICES.md.',
    '',
  ];
  const blocks = packages.map((p) => [
    '-'.repeat(80),
    `${p.name} ${p.version}`,
    `License: ${p.license}`,
    '',
    p.text || '(no license file in the package; see its license field above)',
    '',
  ].join('\n'));
  return `${header.join('\n')}\n${blocks.join('\n')}`;
}

if (require.main === module) {
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  const packages = collect([...Object.keys(pkg.dependencies || {}), ...BUNDLED]);
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, render(packages));
  console.log(`${path.relative(root, OUT)}: ${packages.length} packages`);
}

module.exports = {
  BUNDLED,
  collect,
  render,
};
