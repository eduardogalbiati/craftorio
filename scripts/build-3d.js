// Builds the run's 3D view (src/renderer/run3d/: React + React Three Fiber + three, in JSX) into one
// classic script, generated/run3d-scene.js, that src/renderer/run3d.js loads with a plain
// <script src> the first time the 3D button is clicked (the renderer's CSP is script-src 'self' and
// the rest of the renderer has no bundler). The file is generated, never committed (.gitignore): the
// npm hooks that rebuild the derived docs (prepare, prestart, prebuild) build it too, and the packaged
// app carries it (scripts/package.js packs generated/).
//
//   node scripts/build-3d.js          build (about a second)
//   node scripts/build-3d.js --check  build in memory only: exit 1 when the sources do not compile
//
// Without esbuild (an install without the dev dependencies) it says so and exits 0: the app still
// starts, its 3D button says the view is not built.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ENTRY = path.join(ROOT, 'src', 'renderer', 'run3d', 'main.jsx');
const OUT = path.join(ROOT, 'generated', 'run3d-scene.js');
const BANNER = '// Generated by scripts/build-3d.js from src/renderer/run3d/ (React, React Three Fiber, three): do not edit.\n'
  + '// Loaded by src/renderer/run3d.js on the first click of a run\'s 3D button; defines window.Run3DScene.';

/** esbuild's options for the bundle (`write: false` keeps it in memory). */
function options({ write = true } = {}) {
  return {
    entryPoints: [ENTRY],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['chrome130'],
    jsx: 'automatic',
    loader: { '.jsx': 'jsx' },
    minify: true,
    legalComments: 'eof',
    define: { 'process.env.NODE_ENV': '"production"' },
    banner: { js: BANNER },
    outfile: OUT,
    write,
    logLevel: 'silent',
  };
}

async function build({ write = true } = {}) {
  let esbuild;
  try { esbuild = require('esbuild'); } catch {
    console.warn('build-3d: esbuild is not installed (dev dependencies): the 3D view is not built.');
    return null;
  }
  if (write) fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const result = await esbuild.build(options({ write }));
  const bytes = write ? fs.statSync(OUT).size : result.outputFiles[0].contents.length;
  return { bytes, code: write ? null : result.outputFiles[0].text };
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  build({ write: !check }).then((r) => {
    if (r) console.log(`build-3d: ${check ? 'the sources compile' : path.relative(ROOT, OUT)} (${Math.round(r.bytes / 1024)} KB)`);
  }).catch((e) => {
    console.error(`build-3d: ${e.message}`);
    process.exit(1);
  });
}

module.exports = { build, ENTRY, OUT };
