// Builds the app's two 3D views (React + React Three Fiber + three, in JSX) into classic scripts the
// renderer loads with a plain <script src> on first use (the renderer's CSP is script-src 'self' and
// the rest of the renderer has no bundler):
// - the run's 3D view, packages/ui-kit/run3d/ → generated/run3d-scene.js (window.Run3DScene), loaded by
//   packages/ui-kit/run3d.js the first time the 3D button is clicked;
// - the project city (#373), fronts/analyser/city3d/ → generated/project-city.js
//   (window.ProjectCityScene), loaded by fronts/analyser/views/project/project-city.js the first time
//   the Architecture tab shows its City view.
// The files are generated, never committed (.gitignore): the npm hooks that rebuild the derived docs
// (prepare, prestart, prebuild) build them too, and the packaged app carries them (apps/desktop/scripts/package.js
// packs generated/).
//
//   node scripts/build-3d.js          build both (about a second each)
//   node scripts/build-3d.js --check  build in memory only: exit 1 when the sources do not compile
//
// Without esbuild (an install without the dev dependencies) it says so and exits 0: the app still
// starts, its 3D button and City view say the view is not built.
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ENTRY = path.join(ROOT, 'packages', 'ui-kit', 'run3d', 'main.jsx');
const OUT = path.join(ROOT, 'generated', 'run3d-scene.js');
const BANNER = '// Generated by scripts/build-3d.js from packages/ui-kit/run3d/ (React, React Three Fiber, three): do not edit.\n'
  + '// Loaded by packages/ui-kit/run3d.js on the first click of a run\'s 3D button; defines window.Run3DScene.';
const CITY_ENTRY = path.join(ROOT, 'fronts', 'analyser', 'city3d', 'main.jsx');
const CITY_OUT = path.join(ROOT, 'generated', 'project-city.js');
const CITY_BANNER = '// Generated by scripts/build-3d.js from fronts/analyser/city3d/ (React, React Three Fiber, three): do not edit.\n'
  + '// Loaded by fronts/analyser/views/project/project-city.js on the first City view; defines window.ProjectCityScene.';

// The shared modules a bundle embeds (city-layout.js, architecture-model.js) require packages/shared/i18n.js
// in Node (#23); i18n.js reads its catalogs with fs, which a browser bundle cannot resolve. In a bundle that
// require gets this stub instead: the page's window.I18n (loaded by the renderer), else the English key.
const SHARED_I18N = path.join(ROOT, 'packages', 'shared', 'i18n.js');
const PAGE_I18N = 'const page = () => globalThis.I18n;\n'
  + 'module.exports = { t: (...a) => (page() ? page().t(...a) : a[0]), translated: (k, f, p) => (page() ? page().translated(k, f, p) : f) };\n';
const pageI18n = {
  name: 'page-i18n',
  setup(b) {
    b.onResolve({ filter: /(^|[\\/])i18n(\.js)?$/ }, (args) => {
      const target = path.resolve(args.resolveDir, args.path);
      return target === SHARED_I18N || `${target}.js` === SHARED_I18N ? { path: SHARED_I18N, namespace: 'page-i18n' } : undefined;
    });
    b.onLoad({ filter: /.*/, namespace: 'page-i18n' }, () => ({ contents: PAGE_I18N, loader: 'js' }));
  },
};

/** esbuild's options for one bundle (`write: false` keeps it in memory). */
function options({ write = true, entry = ENTRY, out = OUT, banner = BANNER } = {}) {
  return {
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['chrome130'],
    jsx: 'automatic',
    loader: { '.jsx': 'jsx' },
    minify: true,
    legalComments: 'eof',
    define: { 'process.env.NODE_ENV': '"production"' },
    banner: { js: banner },
    plugins: [pageI18n],
    outfile: out,
    write,
    logLevel: 'silent',
  };
}

/** Builds both bundles: { bytes, code, city: { bytes, code } } (code only in memory), null without esbuild. */
async function build({ write = true } = {}) {
  let esbuild;
  try { esbuild = require('esbuild'); } catch {
    console.warn('build-3d: esbuild is not installed (dev dependencies): the 3D views are not built.');
    return null;
  }
  if (write) fs.mkdirSync(path.dirname(OUT), { recursive: true });
  const one = async (opts) => {
    const result = await esbuild.build(options({ write, ...opts }));
    return { bytes: write ? fs.statSync(opts.out).size : result.outputFiles[0].contents.length, code: write ? null : result.outputFiles[0].text };
  };
  const [run, city] = await Promise.all([
    one({ entry: ENTRY, out: OUT, banner: BANNER }),
    one({ entry: CITY_ENTRY, out: CITY_OUT, banner: CITY_BANNER }),
  ]);
  return { ...run, city };
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  build({ write: !check }).then((r) => {
    if (!r) return;
    const kb = (n) => `${Math.round(n / 1024)} KB`;
    console.log(check
      ? `build-3d: the sources compile (${kb(r.bytes)}, city ${kb(r.city.bytes)})`
      : `build-3d: ${path.relative(ROOT, OUT)} (${kb(r.bytes)}), ${path.relative(ROOT, CITY_OUT)} (${kb(r.city.bytes)})`);
  }).catch((e) => {
    console.error(`build-3d: ${e.message}`);
    process.exit(1);
  });
}

module.exports = {
  build,
  CITY_ENTRY,
  CITY_OUT,
  ENTRY,
  OUT,
};
