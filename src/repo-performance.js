// Repository performance (#159): how well a repository takes parallel runs, for Analytics' "Repository
// performance" tab, and the shared-file counts the Product Owner reads before it plans parallel work
// (#150: `sharedFiles`, one implementation for both).
//   - files most runs edit: each run's own commits, from its commit range in the local clone
//     (`worktree.ready` commit..`local_merge.commit` for a local merge, minus what other runs merged
//     meanwhile; the PR/MR's merge commit, found in `git log` by its number, for PR runs); a run
//     counts once per file; shared files that `npm run docs`-like tools generate are marked;
//   - merge conflicts: runs that went through the conflict step (`resolve_merge` / `resolve_conflict`)
//     or whose `gh pr merge` / `glab mr merge` failed, their share of the runs and of the cost, and the
//     files their conflict messages named (events.jsonl);
//   - parallel work: per day, the peak of runs (and roadmap stages) active at once and the conflicts;
//     the hours of the day runs were active;
//   - before/after: a marker (a date, or a commit of the clone: its commit date) splits the numbers.
// Offline and cheap: run folders, the index (src/store.js caches each run's file list by commit range)
// and `git log`/`git diff`; no model call, no network.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFile } = require('child_process');
const { readEvents } = require('./supervisor');

const CONFLICT_STEPS = new Set(['resolve_conflict', 'resolve_merge']);
const MERGE_COMMAND = /\b(gh\s+pr|glab\s+mr)\s+merge\b/;
// a file edited by more runs than this share is a shared file the epic #158 wants gone
const SHARED_LIMIT = 0.2;
const TOP_FILES = 50;
const GIT_CONCURRENCY = 8;
const GENERATED = /<!-- generated:|\b(auto-?generated|generated by|do not edit)\b/i;
const HOUR = 36e5;

const clip = (s, n) => { s = String(s ?? '').trim(); return s.length > n ? `${s.slice(0, n)}… (${s.length - n} more characters)` : s; };

function git(args, cwd) {
  return new Promise((resolve) => {
    execFile('git', args, { cwd, windowsHide: true, maxBuffer: 64 * 1024 * 1024 }, (err, out) => resolve(err ? null : String(out)));
  });
}

// Merge conflicts a run hit, and the files they name, from its events.jsonl.
function conflictsOf(runDir) {
  const messages = [];
  const files = new Set();
  for (const e of readEvents(runDir)) {
    const msg = e.type === 'log' ? e.message : e.type === 'workflow.finished' ? e.error : null;
    if (!msg || !/conflict/i.test(msg)) continue;
    messages.push(clip(msg, 200));
    // git's conflict kinds, "(modify/delete)", and the branches in "modified in run/x" are not paths
    const text = String(msg).replace(/\([^)]*\)/g, ' ').replace(/\b(deleted|modified|renamed) in\s+\S+/gi, '$1 in');
    // a path with an extension or a folder, or any name git puts in "conflict in X" / "X deleted in"
    // (Dockerfile, Makefile)
    for (const m of text.matchAll(/conflict in\s+([\w@.-]+(?:\/[\w@.-]+)*)|([\w@.-]+(?:\/[\w@.-]+)*)\s+deleted in\b|([\w@.-]+(?:\/[\w@.-]+)*\.[a-z]{1,5}\b|[\w@.-]+(?:\/[\w@.-]+)+)/gi)) {
      files.add((m[1] || m[2] || m[3]).replace(/\.+$/, ''));
    }
  }
  return { count: messages.length, files: [...files].slice(0, 10), messages: messages.slice(0, 3) };
}

// What the events of a run say about its merge: the commit its worktree started from, whether it went
// through the conflict step or a failed PR/MR merge. Cached by the events file's size and time.
const factsCache = new Map();
function runFacts(runDir) {
  const file = path.join(runDir, 'events.jsonl');
  let sig;
  try { const st = fs.statSync(file); sig = `${st.mtimeMs}:${st.size}`; } catch { return { baseCommit: null, conflictStep: null, failedMerge: false, conflictFiles: [] }; }
  const hit = factsCache.get(runDir);
  if (hit?.sig === sig) return hit.facts;
  let baseCommit = null;
  let conflictStep = null;
  let failedMerge = false;
  for (const e of readEvents(runDir)) {
    if (e.type === 'worktree.ready' && !baseCommit && e.commit) baseCommit = e.commit;
    if (e.type === 'step.started' && CONFLICT_STEPS.has(e.step_id)) conflictStep ??= e.step_id;
    if (e.type === 'action.executed' && !e.skipped && e.exit_code !== 0 && MERGE_COMMAND.test(e.command || '')) failedMerge = true;
  }
  const facts = { baseCommit, conflictStep, failedMerge, conflictFiles: conflictStep || failedMerge ? conflictsOf(runDir).files : [] };
  factsCache.set(runDir, { sig, facts });
  return facts;
}

// PR/MR number → its merge commit (a merge or a squash) on the clone's branches.
async function pullRequestCommits(repo) {
  const out = await git(['log', '--branches', '--remotes', '-n', '5000', '--format=%H%x1f%s%x1f%b%x1e'], repo);
  const map = new Map();
  for (const rec of String(out || '').split('\x1e')) {
    const [sha, subject = '', body = ''] = rec.trim().split('\x1f');
    if (!sha) continue;
    const m = subject.match(/^Merge pull request #(\d+)\b/) || subject.match(/\(#(\d+)\)\s*$/) || body.match(/merge request \S*!(\d+)/);
    if (m && !map.has(Number(m[1]))) map.set(Number(m[1]), sha);
  }
  return map;
}

// Each run's commit range in the clone: { args (for git log/diff), key (the cache key) }, or null.
async function commitRanges(runs, repo) {
  const prCommits = runs.some((r) => r.pr?.number && !r.localMerge?.commit) ? await pullRequestCommits(repo) : new Map();
  const base = new Map(runs.map((r) => [r.runId, r.runDir ? runFacts(r.runDir).baseCommit : null]));
  // a resumed run reuses its worktree: its range starts where the first run's did
  const baseOf = (r, seen = new Set()) => {
    const from = r.resumedFrom && !seen.has(r.resumedFrom) && runs.find((x) => x.runId === r.resumedFrom);
    return from ? baseOf(from, seen.add(r.runId)) || base.get(r.runId) : base.get(r.runId);
  };
  const tipOf = (r) => r.localMerge?.commit || (r.pr?.number && prCommits.get(Number(r.pr.number))) || null;
  const merged = runs.filter((r) => r.finishedAt && tipOf(r));
  const ranges = new Map();
  for (const r of runs) {
    if (r.localMerge?.commit && baseOf(r)) {
      // the runs merged while this one ran landed between its start and its (rebased) tip
      const others = merged.filter((o) => o !== r && o.finishedAt < (r.finishedAt || '￿') && o.finishedAt > r.startedAt).map(tipOf).sort();
      const args = [r.localMerge.commit, `^${baseOf(r)}`, ...others.map((c) => `^${c}`)];
      ranges.set(r.runId, { kind: 'log', args, key: crypto.createHash('sha1').update(args.join(' ')).digest('hex') });
    } else if (!r.localMerge?.commit && tipOf(r)) {
      const sha = tipOf(r);
      ranges.set(r.runId, { kind: 'diff', args: [`${sha}^1`, sha], key: `pr:${sha}` });
    }
  }
  return ranges;
}

/**
 * run id → the files its own commits changed, for the runs with a commit range in `repo` (the
 * others are left out). `store`: the workspace index, which keeps each run's list by range.
 */
async function filesEditedByRuns({ runs, repo, store = null }) {
  const out = new Map();
  if (!repo || !fs.existsSync(path.join(repo, '.git'))) return out;
  const ranges = await commitRanges(runs || [], repo);
  const missing = [];
  for (const [runId, range] of ranges) {
    const cached = store?.runFiles?.(runId);
    if (cached && cached.key === range.key) out.set(runId, cached.files);
    else missing.push([runId, range]);
  }
  // a first open of a workspace with hundreds of runs: several git processes at a time, not one by one
  const found = new Map();
  let next = 0;
  const worker = async () => {
    while (next < missing.length) {
      const [runId, range] = missing[next++];
      const text = range.kind === 'log'
        ? await git(['log', '--format=', '--name-only', ...range.args], repo)
        : await git(['diff', '--name-only', ...range.args], repo);
      if (text == null) continue;
      const files = [...new Set(text.split('\n').map((l) => l.trim()).filter(Boolean))].sort();
      store?.putRunFiles?.(runId, range.key, files);
      found.set(runId, files);
    }
  };
  await Promise.all(Array.from({ length: Math.min(GIT_CONCURRENCY, missing.length) }, worker));
  // the ranges' order, whatever order the git calls finished in
  for (const [runId] of missing) if (found.has(runId)) out.set(runId, found.get(runId));
  return out;
}

/** [{ file, runs, share, runIds }] most-edited first, from run id → files (a run counts once per file). */
function fileCounts(filesByRun) {
  const total = filesByRun.size;
  const by = new Map();
  for (const [runId, files] of filesByRun) for (const f of new Set(files)) by.set(f, [...(by.get(f) || []), runId]);
  return [...by].map(([file, runIds]) => ({ file, runs: runIds.length, share: total ? runIds.length / total : 0, runIds }))
    .sort((a, b) => b.runs - a.runs || a.file.localeCompare(b.file));
}

/** The files most of these runs edit (the conflict map the Product Owner reads, #150): fileCounts of filesEditedByRuns. */
async function sharedFiles({ runs, repo, store = null, limit = TOP_FILES }) {
  const byRun = await filesEditedByRuns({ runs, repo, store });
  return { runs: byRun.size, files: fileCounts(byRun).slice(0, limit) };
}

// The file today: its line count (null when it is gone) and whether a tool generates it.
function fileNow(repo, file) {
  let text;
  try { text = fs.readFileSync(path.join(repo, file), 'utf8'); } catch { return { lines: null, generated: false }; }
  return { lines: text ? text.split('\n').length - (text.endsWith('\n') ? 1 : 0) : 0, generated: GENERATED.test(text.slice(0, 65536)) };
}

// #197: what to do with a file over the shared limit, from what is known about it (first rule that
// matches). Deterministic and offline; "Ask for a plan" (analytics:plan) is the model's deeper answer.
const LARGE_LINES = 1000;
const RECOMMENDATIONS = [
  { kind: 'generated', test: (f) => f.generated, text: 'A tool generates this file: edit the generator or its source list instead, and regenerate it after the merge.' },
  { kind: 'test', test: (f) => /(^|\/)(test|tests|__tests__|spec)\//.test(f.file) || /\.(test|spec)\.[a-z]+$/.test(f.file), text: 'Every run adds its tests here: write one test file per feature, next to the existing ones.' },
  { kind: 'stylesheet', test: (f) => /\.(css|scss|sass|less)$/.test(f.file), text: 'A shared stylesheet: move each screen\'s rules to a per-screen CSS file that the screen loads.' },
  { kind: 'doc', test: (f) => /\.(md|mdx|rst|txt)$/i.test(f.file) || /(^|\/)docs?\//.test(f.file), text: 'A shared doc: split it into per-topic docs, or generate its tables from the code.' },
  { kind: 'registry', test: (f) => /(registry|registries|manifest|routes|channels|screens|skills|views|index|list)[^/]*\.[a-z]+$/i.test(f.file) || /^package\.json$/.test(f.file), text: 'A shared registry or list: one file per entry that the registry discovers (a folder it lists), so a feature adds a file instead of editing this one.' },
  { kind: 'large', test: (f) => f.lines >= LARGE_LINES, text: 'A large file touched for unrelated features: split it by area, one module per feature, so runs edit different files.' },
  { kind: 'hotspot', test: () => true, text: 'Many runs edit this file: find which features touch it and move each one\'s part to its own module.' },
];

/** The recommendation for one file of `files` (with `conflicts`: the conflicts that named it), or null under the limit. */
function recommendationOf(f) {
  if (!f || !(f.share > SHARED_LIMIT) || !(f.runs > 1)) return null;
  const rule = RECOMMENDATIONS.find((r) => r.test(f));
  return { kind: rule.kind, text: rule.text, evidence: { share: f.share, runs: f.runs, lines: f.lines ?? null, conflicts: f.conflicts || 0, generated: !!f.generated } };
}

/**
 * The runs split by the Product Owner's Speed ↔ Quality calibration (#189), for the 24/7 tab (#188).
 * `runs` [{ runId, projectId, startedAt, issues, costUsd, conflict, reviewRounds }]; `answers` the
 * Product Owner's plan answers [{ ts, projectId, calibration, groups: [{ issues, stage }] }]. A run
 * takes the calibration of the latest answer before its start that planned one of its issues; runs no
 * answer planned are left out. → [{ calibration, runs, issues, runsPerStage, resolveMergeShare,
 * reviewRounds, costPerIssue, costUsd }] by calibration.
 */
function byCalibration({ runs = [], answers = [] }) {
  const plans = answers.filter((a) => a.calibration && Array.isArray(a.groups)).sort((a, b) => String(b.ts).localeCompare(String(a.ts)));
  const levels = new Map();
  for (const r of runs) {
    const nums = (r.issues || []).map((i) => Number(i?.number ?? i));
    const plan = plans.find((a) => String(a.ts) <= String(r.startedAt) && (!a.projectId || !r.projectId || a.projectId === r.projectId)
      && a.groups.some((g) => (g.issues || []).some((n) => nums.includes(Number(n)))));
    if (!plan) continue;
    if (!levels.has(plan.calibration)) levels.set(plan.calibration, { runs: [], plans: new Set() });
    levels.get(plan.calibration).runs.push(r);
    levels.get(plan.calibration).plans.add(plan);
  }
  return [...levels].sort(([a], [b]) => a - b).map(([calibration, { runs: list, plans: used }]) => {
    const issues = list.reduce((s, r) => s + (r.issues || []).length, 0);
    const costUsd = list.reduce((s, r) => s + (r.costUsd || 0), 0);
    const groups = [...used].flatMap((a) => a.groups);
    const stages = [...used].reduce((s, a) => s + new Set(a.groups.map((g) => g.stage || 1)).size, 0);
    return {
      calibration, runs: list.length, issues, costUsd,
      runsPerStage: stages ? groups.length / stages : null,
      resolveMergeShare: list.length ? list.filter((r) => r.conflict).length / list.length : 0,
      reviewRounds: list.length ? list.reduce((s, r) => s + (r.reviewRounds || 0), 0) / list.length : 0,
      costPerIssue: issues ? costUsd / issues : null,
    };
  });
}

const endOf = (r, now) => Date.parse(r.finishedAt || '') || (r.status === 'running' ? now : Date.parse(r.startedAt) + (r.durationMs || 0));
const pad = (n) => String(n).padStart(2, '0');
const localDay = (t) => { const d = new Date(t); return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`; };

// The most runs active at the same moment among `runs`, and those runs.
function peakOf(runs, now) {
  const points = runs.flatMap((r) => [[Date.parse(r.startedAt), 1, r], [endOf(r, now), -1, r]]).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const active = new Set();
  let peak = [];
  for (const [, d, r] of points) {
    if (d > 0) active.add(r); else active.delete(r);
    if (active.size > peak.length) peak = [...active];
  }
  return peak;
}

// Per local day: runs started, the peak of runs (and roadmap stages) at once, runs that hit a conflict.
function parallelWork(runs, { conflicted, stageOf, now }) {
  const days = new Map();
  for (const r of runs) {
    const day = localDay(Date.parse(r.startedAt));
    days.set(day, [...(days.get(day) || []), r]);
  }
  const hours = Array(24).fill(0);
  for (const r of runs) {
    const seen = new Set();
    for (let t = Date.parse(r.startedAt); t < endOf(r, now) && seen.size < 24; t += HOUR) seen.add(new Date(t).getHours());
    for (const h of seen) hours[h]++;
  }
  return {
    days: [...days].sort(([a], [b]) => a.localeCompare(b)).map(([day, list]) => {
      const peak = peakOf(runs.filter((r) => list.includes(r) || (Date.parse(r.startedAt) < Date.parse(`${day}T23:59:59`) && endOf(r, now) > Date.parse(`${day}T00:00:00`))), now);
      return { day, runs: list.length, peak: peak.length, stages: new Set(peak.map(stageOf).filter(Boolean)).size, conflicts: list.filter((r) => conflicted.has(r.runId)).length };
    }),
    hours,
  };
}

// The numbers the epic #158 sets targets on, for one set of runs.
function summarize(runs, { filesByRun, conflicted, now }) {
  const own = new Map([...filesByRun].filter(([id]) => runs.some((r) => r.runId === id)));
  const counts = fileCounts(own);
  const cost = runs.reduce((a, r) => a + (r.costUsd || 0), 0);
  const hit = runs.filter((r) => conflicted.has(r.runId));
  const hitCost = hit.reduce((a, r) => a + (r.costUsd || 0), 0);
  return {
    runs: runs.length,
    runsWithCommits: own.size,
    costUsd: cost,
    topFile: counts[0] ? { file: counts[0].file, share: counts[0].share } : null,
    // a file only one run edited is not shared, whatever its share of a few runs
    filesOverLimit: counts.filter((c) => c.runs > 1 && c.share > SHARED_LIMIT).length,
    conflictRuns: hit.length,
    conflictShare: runs.length ? hit.length / runs.length : 0,
    conflictCostShare: cost ? hitCost / cost : 0,
    peak: peakOf(runs, now).length,
  };
}

/**
 * The Repository performance tab of one project: `runs` are its RunInfos (src/runs.js), `repo` its
 * local clone, `from`/`to` the range (YYYY-MM-DD, the run's start), `marker` a date or a commit,
 * `stages` [{ name, runIds }] of its roadmap. Simulated runs are left out.
 */
async function repositoryPerformance({ runs, repo, store = null, from, to, marker = '', stages = [], now = Date.now() }) {
  const inRange = (runs || []).filter((r) => !r.mock && r.startedAt && (!from || r.startedAt.slice(0, 10) >= from) && (!to || r.startedAt.slice(0, 10) <= to))
    .sort((a, b) => String(a.startedAt).localeCompare(String(b.startedAt)));
  // the merges of the runs before the range still bound the first runs' commit ranges
  const filesByRun = await filesEditedByRuns({ runs: (runs || []).filter((r) => !r.mock && r.startedAt), repo, store });
  for (const id of filesByRun.keys()) if (!inRange.some((r) => r.runId === id)) filesByRun.delete(id);
  const conflicted = new Map();
  for (const r of inRange) {
    const f = r.runDir ? runFacts(r.runDir) : null;
    if (f?.conflictStep || f?.failedMerge) conflicted.set(r.runId, f);
  }
  const stageNames = new Map(stages.flatMap((s) => s.runIds.map((id) => [id, s.name])));
  const stageOf = (r) => stageNames.get(r.runId) || null;

  const named = (file) => [...conflicted.values()].filter((f) => f.conflictFiles.some((x) => x === file || file.endsWith(`/${x}`))).length;
  const files = fileCounts(filesByRun).slice(0, TOP_FILES).map(({ runIds, ...c }) => {
    const row = { ...c, ...fileNow(repo, c.file) };
    const recommendation = recommendationOf({ ...row, conflicts: named(c.file) });
    return recommendation ? { ...row, recommendation } : row;
  });
  const total = summarize(inRange, { filesByRun, conflicted, now });
  const hit = inRange.filter((r) => conflicted.has(r.runId));

  let compare = null;
  const value = String(marker || '').trim();
  if (value) {
    let at = /^\d{4}-\d{2}-\d{2}/.test(value) ? Date.parse(value.length === 10 ? `${value}T00:00:00` : value) : null;
    let commit = null;
    if (at == null && /^[\w./^~-]+$/.test(value) && !value.startsWith('-')) {
      const out = await git(['show', '-s', '--format=%H %cI', value], repo);
      const [sha, date] = String(out || '').trim().split(' ');
      if (date) { commit = sha; at = Date.parse(date); }
    }
    if (at == null || Number.isNaN(at)) compare = { marker: value, error: `"${value}" is neither a date (YYYY-MM-DD) nor a commit of ${repo || 'the repository'}.` };
    else {
      const side = (list) => summarize(list, { filesByRun, conflicted, now });
      compare = {
        marker: value, commit, at: new Date(at).toISOString(),
        before: side(inRange.filter((r) => Date.parse(r.startedAt) < at)),
        after: side(inRange.filter((r) => Date.parse(r.startedAt) >= at)),
      };
    }
  }

  return {
    from, to,
    ...total,
    sharedLimit: SHARED_LIMIT,
    empty: !total.runsWithCommits && !hit.length,
    files,
    conflicts: hit.map((r) => {
      const f = conflicted.get(r.runId);
      return {
        runId: r.runId, title: r.title || r.workflow || r.runId, workflow: r.workflow, status: r.status, startedAt: r.startedAt,
        costUsd: r.costUsd || 0, via: f.conflictStep || 'failed PR/MR merge', files: f.conflictFiles,
      };
    }).reverse(),
    parallel: parallelWork(inRange, { conflicted, stageOf, now }),
    compare,
  };
}

